class PathSafetyError(RuntimeError):
    """An output path would clobber a read-only input or a protected artifact.

    Raised *before* anything is opened for writing. Every message names the
    rule that fired, so a refusal is diagnosable without reading this module.
    """


def _resolved(path: str | Path) -> Path:
    return Path(path).expanduser().resolve()


def assert_output_path_is_safe(
    path: str | Path,
    *,
    kind: str = "corpus",
    inputs: tuple[Path, ...] | list[Path] = (),
    what: str = "output",
) -> Path:
    """Gate every write target of a translation stage. Returns the resolved path.

    ``kind="corpus"`` is for anything carrying translated text -- response logs,
    applied rows, provenance sidecars. It must live under ``CORPUS_WRITE_ROOTS``.

    ``kind="metadata"`` is for text-free manifests and reports. It is *not*
    confined to a write root: a manifest carries no corpus payload, so confining
    it protects nothing. The clobber rules below still apply to it in full.

    ``inputs`` are this run's read-only inputs (its request file, its pilot log).
    They are refused as write targets on top of the repository-wide
    ``READ_ONLY_INPUTS``, because "output equals input" is the one mistake that
    destroys the thing it was derived from.
    """
    if kind not in {"corpus", "metadata"}:
        raise ValueError(f"unknown path kind {kind!r}")

    resolved = _resolved(path)
    forbidden_inputs = {_resolved(p) for p in (*READ_ONLY_INPUTS, *inputs)}

    if resolved in forbidden_inputs:
        raise PathSafetyError(
            f"refusing to write the {what} to {resolved}: that path is a read-only "
            "input to this run. An output may never be its own input."
        )
    if resolved.is_relative_to(_resolved(PROCESSED_DIR)):
        raise PathSafetyError(
            f"refusing to write the {what} to {resolved}: data/processed/ holds the "
            "v1 frozen dataset and splits, which no translation stage may write."
        )
    if resolved.is_relative_to(_resolved(V2_PROCESSED_DIR)):
        raise PathSafetyError(
            f"refusing to write the {what} to {resolved}: data/v2/processed/ is the "
            "frozen-dataset destination and is not written before the freeze stage."
        )
    if resolved in {_resolved(p) for p in PROTECTED_PILOT_ARTIFACTS}:
        raise PathSafetyError(
            f"refusing to write the {what} to {resolved}: that is a reviewed pilot "
            "artifact. Pilot logs are read to reuse completed work, never written."
        )
    if resolved.is_relative_to(_resolved(CPU_PILOT_ARCHIVE_DIR)):
        raise PathSafetyError(
            f"refusing to write the {what} to {resolved}: that is the pilot archive, "
            "which exists to stay byte-identical to the originals."
        )

    if kind == "corpus":
        v2_root = _resolved(V2_DIR)
        v2_interim = _resolved(V2_INTERIM_DIR)
        if resolved.is_relative_to(v2_root) and not resolved.is_relative_to(v2_interim):
            raise PathSafetyError(
                f"refusing to write the {what} to {resolved}: dataset-v2 corpus output "
                f"must be under {V2_INTERIM_DIR.relative_to(REPO_ROOT)}/ "
                "(data/v2/manifests/ is metadata only; data/v2/processed/ is the freeze)."
            )
        if not any(resolved.is_relative_to(_resolved(r)) for r in CORPUS_WRITE_ROOTS):
            roots = ", ".join(str(r.relative_to(REPO_ROOT)) + "/" for r in CORPUS_WRITE_ROOTS)
            raise PathSafetyError(
                f"refusing to write the {what} to {resolved}: translated text may only "
                f"be written under {roots}"
            )
    return resolved


def run_results_dir(run_id: str) -> Path:
    """``results/<run_id>/`` -- every artifact is keyed by run ID."""
    return RESULTS_DIR / run_id


def run_logs_dir(run_id: str) -> Path:
    """``logs/<run_id>/`` -- every log is keyed by run ID."""
    return LOGS_DIR / run_id


def display_path(path: str | Path) -> str:
    """Human-readable form of ``path`` for console output.

    Repo-relative when the path lies inside the repository, so log lines stay
    short and copy-pasteable; otherwise the path exactly as it was given.

    Exists because ``Path.relative_to`` is a pure string operation that does not
    resolve: a perfectly valid relative CLI argument such as
    ``--out data/v2/interim/x.jsonl`` is not lexically under the absolute
    ``REPO_ROOT``, so reporting it raised ``ValueError`` *after* the output file
    had already been written. Resolving first fixes the common case; the
    fallback covers paths genuinely outside the repository.

    Display only. Never open, write, or compare a path via this result -- it is
    deliberately lossy (the fallback returns the caller's original string).
    """
    original = Path(path)
    try:
        resolved = original.resolve()
    except OSError:                       # pragma: no cover - platform dependent
        return str(original)
    if resolved.is_relative_to(REPO_ROOT):
        return str(resolved.relative_to(REPO_ROOT))
    return str(original)
